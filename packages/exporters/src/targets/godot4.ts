import { packZip } from '../codec/zip.js';
import type {
  BakedExportData,
  ExportBundle,
  Godot4ExportOptions,
  PackedSprite,
} from '../types.js';

function sanitizeId(raw: string): string {
  return raw.replace(/[^a-zA-Z0-9_]+/g, '_');
}

function buildGodotImportFile(
  atlasResPath: string,
  textureFilter: 'linear' | 'nearest',
): string {
  // Godot 4 .import preset: lossless RGBA, no mipmaps, fix_alpha_border prevents dark halos on HD sprites
  return [
    '[remap]',
    '',
    'importer="texture"',
    'type="CompressedTexture2D"',
    '',
    '[deps]',
    '',
    `source_file="${atlasResPath}"`,
    '',
    '[params]',
    '',
    'compress/mode=0',
    'compress/high_quality=false',
    'compress/lossy_quality=1.0',
    'compress/hdr_compression=1',
    'compress/normal_map=0',
    'compress/channel_pack=0',
    'mipmaps/generate=false',
    'mipmaps/limit=-1',
    'roughness/mode=0',
    'roughness/src_normal=""',
    'process/fix_alpha_border=true',
    'process/premult_alpha=false',
    'process/normal_map_invert_y=false',
    'process/hdr_as_srgb=false',
    'process/hdr_clamp_exposure=false',
    'process/size_limit=0',
    'detect_3d/compress_to=0',
    `# Recommended Node texture_filter: ${textureFilter === 'nearest' ? 'TEXTURE_FILTER_NEAREST (1)' : 'TEXTURE_FILTER_LINEAR (2)'}`,
    '',
  ].join('\n');
}

function buildGodotSpriteFramesTres(
  baked: BakedExportData,
  atlasResPath: string,
): string {
  const spriteMap = new Map<string, { sprite: PackedSprite; subId: string }>();
  const subResourceBlocks: string[] = [];

  baked.atlas.sprites.forEach((sprite, idx) => {
    const subId = `AtlasTexture_${String(idx).padStart(4, '0')}_${sanitizeId(sprite.id.replace(/\.png$/i, ''))}`;
    spriteMap.set(sprite.id, { sprite, subId });

    const { x, y, width, height } = sprite.rect;
    const { x: trimX, y: trimY } = sprite.trimOffset;
    const marginW = Math.max(0, sprite.sourceSize.width - width);
    const marginH = Math.max(0, sprite.sourceSize.height - height);

    subResourceBlocks.push(
      [
        `[sub_resource type="AtlasTexture" id="${subId}"]`,
        'atlas = ExtResource("1_atlas")',
        `region = Rect2(${x}, ${y}, ${width}, ${height})`,
        `margin = Rect2(${trimX}, ${trimY}, ${marginW}, ${marginH})`,
        'filter_clip = true',
      ].join('\n'),
    );
  });

  const loadSteps = 2 + baked.atlas.sprites.length;

  const animBlocks = baked.animations.map((anim) => {
    const frameEntries = anim.frameIds
      .map((fid) => {
        const entry = spriteMap.get(fid);
        if (!entry) return null;
        return `{\n"duration": 1.0,\n"texture": SubResource("${entry.subId}")\n}`;
      })
      .filter(Boolean)
      .join(', ');

    return [
      '{',
      `"frames": [${frameEntries}],`,
      `"loop": ${anim.loop ? 'true' : 'false'},`,
      `"name": &"${anim.name}",`,
      `"speed": ${anim.fps.toFixed(1)}`,
      '}',
    ].join('\n');
  });

  return [
    `[gd_resource type="SpriteFrames" load_steps=${loadSteps} format=3]`,
    '',
    `[ext_resource type="Texture2D" path="${atlasResPath}" id="1_atlas"]`,
    '',
    subResourceBlocks.join('\n\n'),
    '',
    '[resource]',
    `animations = [${animBlocks.join(', ')}]`,
    '',
  ].join('\n');
}

function buildGodotSceneTscn(
  baked: BakedExportData,
  framesResPath: string,
  scriptResPath: string,
  textureFilter: 'linear' | 'nearest',
): string {
  const defaultAnim = baked.animations[0]?.name ?? 'idle_SE';
  // Offset shifts sprite upward so Node2D origin (0,0) sits right on the character's feet for isometric Y-sorting!
  const offsetY = Math.round(-(baked.footAnchor.y - baked.frameSize.height * 0.5));
  const filterCode = textureFilter === 'nearest' ? 1 : 2;

  return [
    '[gd_scene load_steps=3 format=3]',
    '',
    `[ext_resource type="SpriteFrames" path="${framesResPath}" id="1_frames"]`,
    `[ext_resource type="Script" path="${scriptResPath}" id="2_script"]`,
    '',
    `[node name="${baked.characterName}" type="AnimatedSprite2D"]`,
    `texture_filter = ${filterCode}`,
    'sprite_frames = ExtResource("1_frames")',
    `animation = &"${defaultAnim}"`,
    `offset = Vector2(0, ${offsetY})`,
    'script = ExtResource("2_script")',
    '',
  ].join('\n');
}

function buildGodotHelperScript(baked: BakedExportData): string {
  const first = baked.animations[0];
  return `extends AnimatedSprite2D
## Auto-generated by PaperDollKit v2 (Baked SpriteFrames Controller)
## Drop this folder into your Godot 4 project and call play_state("walk", "SE")

@export var current_action: String = "${first?.actionId ?? 'idle'}"
@export var current_direction: String = "${first?.directionId ?? 'SE'}"

func _ready() -> void:
\tplay_state(current_action, current_direction)

func play_state(action: String, direction: String) -> void:
\tcurrent_action = action
\tcurrent_direction = direction
\tvar anim_name := "%s_%s" % [action, direction]
\tif sprite_frames and sprite_frames.has_animation(anim_name):
\t\tif animation != anim_name or not is_playing():
\t\t\tplay(anim_name)
`;
}

function buildGodotReadme(baked: BakedExportData, resBasePath: string): string {
  const animList = baked.animations.map((a) => `- \`${a.name}\` (${a.frameIds.length} frames @ ${a.fps} fps, loop=${a.loop})`).join('\n');
  return `# ${baked.characterName} — Godot 4.x Baked SpriteFrames Export

Generated by **PaperDollKit v2** (Mode A: High-Performance Single-Sprite Baked Atlas).

## Quick Import (3 Steps)
1. Copy this folder into your Godot 4 project at \`${resBasePath}\`.
2. Open Godot 4 — the engine automatically imports \`${baked.characterName}_atlas.png\` with lossless alpha-border protection.
3. Drag \`${baked.characterName}.tscn\` into your isometric scene (origin \`(0, 0)\` is already aligned at the character's feet for \`y_sort_enabled\`).

## Script Usage
\`\`\`gdscript
$Hero.play_state("walk", "SE")
$Hero.play_state("attack", "SW")
\`\`\`

## Included Animations (${baked.animations.length})
${animList}
`;
}

/**
 * Generates a complete Godot 4.x Baked SpriteFrames asset bundle (`.png`, `.png.import`,
 * `_frames.tres`, `.tscn`, `_controller.gd`, `README_GODOT4.md`) and packs it into a ZIP.
 */
export function exportGodot4BakedBundle(
  baked: BakedExportData,
  opts: Godot4ExportOptions = {},
): ExportBundle {
  const name = baked.characterName;
  const resBase = (opts.resBasePath ?? `res://assets/characters/${name}`).replace(/\/+$/, '');
  const filter = opts.textureFilter ?? 'linear';

  const atlasFile = `${name}_atlas.png`;
  const framesFile = `${name}_frames.tres`;
  const sceneFile = `${name}.tscn`;
  const scriptFile = `${name}_controller.gd`;

  const atlasResPath = `${resBase}/${atlasFile}`;
  const framesResPath = `${resBase}/${framesFile}`;
  const scriptResPath = `${resBase}/${scriptFile}`;

  const files: Record<string, Uint8Array | string> = {
    [`${name}/${atlasFile}`]: baked.atlas.png,
    [`${name}/${atlasFile}.import`]: buildGodotImportFile(atlasResPath, filter),
    [`${name}/${framesFile}`]: buildGodotSpriteFramesTres(baked, atlasResPath),
    [`${name}/${sceneFile}`]: buildGodotSceneTscn(baked, framesResPath, scriptResPath, filter),
    [`${name}/${scriptFile}`]: buildGodotHelperScript(baked),
    [`${name}/README_GODOT4.md`]: buildGodotReadme(baked, resBase),
  };

  return {
    files,
    zip: packZip(files),
    zipFilename: `${name}_godot4.zip`,
  };
}
